# tools/popiersie_pl/instaluj.py - nowe popiersia z PixelLab do gry (2026-11-17).
#
#   python tools/popiersie_pl/instaluj.py            -> instaluje (kopia starych w ..\Tawerna_archiwum_2026-11-08\popiersia_<czas>\)
#
#  1. ludzie: tools/busts_pl/staging/<Key>_Bust.png (128x128) -> img/pictures/<Key>_Bust.png (256x256, x2 najbliższy sąsiad)
#  2. bohater: tools/popiersie_pl/baza.png -> img/pictures/Hero_Bust.png i Hero_Bust_Baza.png (baza do składania - nazwa, której
#     nie przechwytuje stary Ubior.bust), warstwy/<rodzina>(.png|_ukryj.png) -> img/pictures/popiersie/ (x2)
#  3. js/plugins/Popiersie_Data.js z tools/popiersie_pl/warstwy.json (rodziny: plik, maska, miejsce, kolejność, wzory, przedmioty)
import os, sys, json, shutil, time
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.abspath(os.path.join(HERE, "..", ".."))
PIC = os.path.join(GAME, "img", "pictures")
OUT_LAYERS = os.path.join(PIC, "popiersie")
STAGING = os.path.join(GAME, "tools", "busts_pl", "staging")
ARCH = os.path.abspath(os.path.join(GAME, "..", "Tawerna_archiwum_2026-11-08", "popiersia_" + time.strftime("%Y%m%d_%H%M%S")))
SCALE = 2


def x2(src, dst):
    im = Image.open(src).convert("RGBA")
    im = im.resize((im.size[0] * SCALE, im.size[1] * SCALE), Image.NEAREST)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    im.save(dst)
    return im.size


def main():
    os.makedirs(ARCH, exist_ok=True)
    # the old busts first
    old = [f for f in os.listdir(PIC) if f.endswith("_Bust.png") or f.startswith("Hero_Bust")]
    for f in old:
        shutil.copy2(os.path.join(PIC, f), os.path.join(ARCH, f))
    print("kopia starych popiersi:", len(old), "->", ARCH)
    # 1. the people
    n = 0
    for f in sorted(os.listdir(STAGING)):
        if not f.endswith("_Bust.png") or f.startswith("Hero_"):
            continue
        x2(os.path.join(STAGING, f), os.path.join(PIC, f))
        n += 1
    print("popiersia ludzi:", n)
    # 2. the hero: the base (twice: the name the game asks for, and the one the composer reads) and the layers
    base = os.path.join(HERE, "baza.png")
    x2(base, os.path.join(PIC, "Hero_Bust.png"))
    x2(base, os.path.join(PIC, "Hero_Bust_Baza.png"))
    W = json.load(open(os.path.join(HERE, "warstwy.json"), encoding="utf-8"))
    fams = {}
    for k, v in W.items():
        if k.startswith("_"):
            continue
        x2(os.path.join(HERE, v["plik"]), os.path.join(OUT_LAYERS, k + ".png"))
        mask = None
        if v.get("ukryj") and os.path.exists(os.path.join(HERE, v["ukryj"])):
            x2(os.path.join(HERE, v["ukryj"]), os.path.join(OUT_LAYERS, k + "_ukryj.png"))
            mask = "popiersie/" + k + "_ukryj"
        fams[k] = {"plik": "popiersie/" + k, "ukryj": mask, "miejsce": v["miejsce"], "kolejnosc": v["kolejnosc"],
                   "wzory": v.get("wzory") or [], "przedmioty": v.get("przedmioty") or [], "wlosy": bool(v.get("ukrywa_wlosy"))}
    print("warstwy bohatera:", len(fams))
    # 3. the data plugin
    js = ("//=============================================================================\n"
          "// Popiersie_Data.js - generated by tools/popiersie_pl/instaluj.py (do not edit by hand)\n"
          "//=============================================================================\n"
          "/*:\n * @target MZ\n * @plugindesc Popiersie bohatera - dane: warstwy ekwipunku na portrecie (PixelLab, 2026-11-17). v1.0.0\n"
          " * @author Claude\n *\n * @help Dane dla Popiersie.js: rodziny warstw (plik, maska wymazania, miejsce, kolejność, wzory, przedmioty).\n */\n"
          "window.PopiersieData = " + json.dumps({"BAZA": "Hero_Bust_Baza", "ROZMIAR": 256, "RODZINY": fams,
                                                   "NIEWIDOCZNE": W.get("_niewidoczne_na_popiersiu", [])}, ensure_ascii=False, indent=1) + ";\n")
    open(os.path.join(GAME, "js", "plugins", "Popiersie_Data.js"), "w", encoding="utf-8", newline="\n").write(js)
    print("js/plugins/Popiersie_Data.js zapisany")


if __name__ == "__main__":
    main()
