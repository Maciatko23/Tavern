def glyph(ch, font):
    """rows of the glyph and the marks (list of (dx, dy) extra pixels, dy -1 above / 5|7 below)"""
    ch = ch.upper() if ch.upper() in (F35 if font == "3x5" else F57) or ch.upper() in PL else ch
    table = F35 if font == "3x5" else F57
    if ch in table:
        return table[ch], []
    if ch in PL:
        base, where, mark = PL[ch]
        rows = table.get(base, table[" "])
        marks = []
        if where and mark:
            w = len(rows[0])
            off = (w - 3) // 2 + (w - 3) % 2 if w > 3 else 0
            for i, c in enumerate(mark):
                if c == "#": marks.append((i + off, -1 if where == "above" else len(rows)))
        return rows, marks
    return table[" "], []

def width(text, font="3x5", spacing=1):
    return sum(len(glyph(c, font)[0][0]) + spacing for c in text) - spacing

def draw(img, x, y, text, colour, font="3x5", spacing=1, shadow=None):
    """paint `text` with its top-left at (x, y); shadow: a colour drawn one pixel lower (letters stand out)"""
    px = img.load()
    W, H = img.size
    def put(xx, yy, c):
        if 0 <= xx < W and 0 <= yy < H: px[xx, yy] = c
    cx = x
    for ch in text:
        rows, marks = glyph(ch, font)
        for layer, col, oy in ((0, shadow, 1), (1, colour, 0)) if shadow else ((1, colour, 0),):
            for ry, row in enumerate(rows):
                for rx, c in enumerate(row):
                    if c == "#": put(cx + rx, y + ry + oy, col)
            for (mx, my) in marks: put(cx + mx, y + my + oy, col)
        cx += len(rows[0]) + spacing
    return cx - spacing
