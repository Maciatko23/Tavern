// The plugin lists in Node (tests/run.js, the tests): the game's list js/tawerna_wtyczki.js (the game's plugins, in order, with
// their parameters) and the editor's part js/plugins.js (TawernaLoader + the plugins whose parameters are set in the editor), and
// what the page's $plugins comes out as - merge(): the rules of js/plugins/TawernaLoader.js, written again by another hand so that
// tests/ladowacz_test.js checks the loader against it. docs/ARCHITEKTURA.md, section 2.
//
//   const W = require("./lib/wtyczki.js");
//   W.lista()   the game's list (entries)        W.edytor()  js/plugins.js's entries
//   W.nazwy()   the page's $plugins names         W.tekst()   both files' text (a quick /"name":"X"/ test)
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const LISTA = path.join(ROOT, "js", "tawerna_wtyczki.js");
const PLUGINS_JS = path.join(ROOT, "js", "plugins.js");
const LOADER = "TawernaLoader";

// the entries of a list file (or of its text): the array between the first "[" and the last "]"
function parse(fileOrText) {
    const s = /\n/.test(fileOrText) ? fileOrText : fs.readFileSync(fileOrText, "utf8");
    return JSON.parse(s.slice(s.indexOf("["), s.lastIndexOf("]") + 1));
}
const lista = () => parse(LISTA);
const edytor = () => parse(PLUGINS_JS);
const tekst = () => [LISTA, PLUGINS_JS].map(f => (fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "")).join("\n");
// a js/plugins.js text as the editor writes it
const plikEdytora = entries => "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n" + entries.map(e => JSON.stringify(e)).join(",\n") + "\n];\n";

// the plugin list the page gets (TawernaLoader.js's rules): the game's list in order, each name once; a plugin in js/plugins.js
// too takes on/off from there and its parameters key by key; js/plugins.js's own plugins above the TawernaLoader entry before the
// list, below it after the list; no TawernaLoader entry (an old save) - each right after the one above it in js/plugins.js
function merge(list, editor) {
    const name = p => String(p.name).split("/").pop();
    editor = editor.filter(p => p && p.name);
    const ed = {};
    for (const p of editor) if (!(name(p) in ed)) ed[name(p)] = p;
    const used = new Set([LOADER]), base = [];
    for (const m of list) {
        const n = name(m);
        if (used.has(n)) continue;
        used.add(n);
        const e = ed[n];
        base.push(e ? Object.assign({}, m, { status: !!e.status, parameters: Object.assign({}, m.parameters || {}, e.parameters || {}) }) : m);
    }
    const own = ed[LOADER] || { name: LOADER, status: true, description: "", parameters: {} };
    const li = editor.findIndex(p => name(p) === LOADER);
    const fresh = p => { const n = name(p); if (used.has(n)) return false; used.add(n); return true; };
    if (li >= 0) return editor.slice(0, li).filter(fresh).concat([own], base, editor.slice(li + 1).filter(fresh));
    const out = [own].concat(base);
    let at = 0;
    for (const p of editor) {
        if (fresh(p)) { out.splice(++at, 0, p); continue; }
        const i = out.findIndex(q => name(q) === name(p));
        if (i >= 0) at = i;
    }
    return out;
}
const nazwy = () => merge(lista(), edytor()).map(p => p.name);

module.exports = { ROOT, LISTA, PLUGINS_JS, LOADER, parse, lista, edytor, tekst, plikEdytora, merge, nazwy };
